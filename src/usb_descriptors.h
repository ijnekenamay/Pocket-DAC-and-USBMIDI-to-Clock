#pragma once

#include "audio_config.h"

enum {
    ITF_NUM_AUDIO_CONTROL = 0,
    ITF_NUM_AUDIO_STREAMING,
    ITF_NUM_MIDI_CONTROL,
    ITF_NUM_MIDI_STREAMING,
    ITF_NUM_TOTAL
};

#define UAC2_ENTITY_CLOCK 0x04
#define UAC2_ENTITY_SPEAKER_INPUT 0x01
#define UAC2_ENTITY_SPEAKER_OUTPUT 0x03

#define TUD_AUDIO_SPEAKER_STEREO_DESC_LEN \
    (TUD_AUDIO_DESC_IAD_LEN + TUD_AUDIO_DESC_STD_AC_LEN + TUD_AUDIO_DESC_CS_AC_LEN + \
     TUD_AUDIO_DESC_CLK_SRC_LEN + TUD_AUDIO_DESC_INPUT_TERM_LEN + TUD_AUDIO_DESC_OUTPUT_TERM_LEN + \
     2 * TUD_AUDIO_DESC_STD_AS_INT_LEN + TUD_AUDIO_DESC_CS_AS_INT_LEN + \
     TUD_AUDIO_DESC_TYPE_I_FORMAT_LEN + TUD_AUDIO_DESC_STD_AS_ISO_EP_LEN + \
    TUD_AUDIO_DESC_CS_AS_ISO_EP_LEN + TUD_AUDIO_DESC_STD_AS_ISO_FB_EP_LEN)

#define TUD_AUDIO_SPEAKER_STEREO_DESCRIPTOR(_stridx, _epout, _epfb) \
    TUD_AUDIO_DESC_IAD(ITF_NUM_AUDIO_CONTROL, 2, 0), \
    TUD_AUDIO_DESC_STD_AC(ITF_NUM_AUDIO_CONTROL, 0, _stridx), \
    TUD_AUDIO_DESC_CS_AC(0x0200, AUDIO_FUNC_DESKTOP_SPEAKER, \
        TUD_AUDIO_DESC_CLK_SRC_LEN + TUD_AUDIO_DESC_INPUT_TERM_LEN + TUD_AUDIO_DESC_OUTPUT_TERM_LEN, \
        AUDIO_CS_AS_INTERFACE_CTRL_LATENCY_POS), \
    TUD_AUDIO_DESC_CLK_SRC(UAC2_ENTITY_CLOCK, 3, 7, 0, 0), \
    TUD_AUDIO_DESC_INPUT_TERM(UAC2_ENTITY_SPEAKER_INPUT, AUDIO_TERM_TYPE_USB_STREAMING, 0, \
        UAC2_ENTITY_CLOCK, 2, AUDIO_CHANNEL_CONFIG_NON_PREDEFINED, 0, 0, 0), \
    TUD_AUDIO_DESC_OUTPUT_TERM(UAC2_ENTITY_SPEAKER_OUTPUT, AUDIO_TERM_TYPE_OUT_ROOM_SPEAKER, 0, \
        UAC2_ENTITY_SPEAKER_INPUT, UAC2_ENTITY_CLOCK, 0, 0), \
    TUD_AUDIO_DESC_STD_AS_INT(ITF_NUM_AUDIO_STREAMING, 0, 0, 4), \
    TUD_AUDIO_DESC_STD_AS_INT(ITF_NUM_AUDIO_STREAMING, 1, 2, 4), \
    TUD_AUDIO_DESC_CS_AS_INT(UAC2_ENTITY_SPEAKER_INPUT, AUDIO_CTRL_NONE, AUDIO_FORMAT_TYPE_I, \
        AUDIO_DATA_FORMAT_TYPE_I_PCM, PICOINTERFACE_AUDIO_CHANNEL_COUNT, AUDIO_CHANNEL_CONFIG_NON_PREDEFINED, 0), \
    TUD_AUDIO_DESC_TYPE_I_FORMAT(PICOINTERFACE_AUDIO_SUBSLOT_BYTES, PICOINTERFACE_AUDIO_BIT_RESOLUTION), \
    TUD_AUDIO_DESC_STD_AS_ISO_EP(_epout, \
        (TUSB_XFER_ISOCHRONOUS | TUSB_ISO_EP_ATT_ASYNCHRONOUS | TUSB_ISO_EP_ATT_DATA), \
        CFG_TUD_AUDIO_UNC_1_FORMAT_1_EP_SZ_OUT, 1), \
    TUD_AUDIO_DESC_CS_AS_ISO_EP(AUDIO_CS_AS_ISO_DATA_EP_ATT_NON_MAX_PACKETS_OK, AUDIO_CTRL_NONE, \
        AUDIO_CS_AS_ISO_DATA_EP_LOCK_DELAY_UNIT_MILLISEC, 1), \
    TUD_AUDIO_DESC_STD_AS_ISO_FB_EP(_epfb, 1)
